(async () => {
  const w = window.__sunlight, api = window.sunlight;
  const out = { passed: 0, failed: [], errors: [] };
  const check = (label, value) => { if (value) out.passed++; else out.failed.push(label); };
  const wait = (ms) => new Promise((r) => setTimeout(r, ms));
  const waitFor = async (fn) => { for (let i = 0; i < 160; i++) { if (fn()) return true; await wait(50); } return false; };
  window.addEventListener('error', (e) => out.errors.push(e.message));
  await w.setRoot(DEMO);
  await api.fs.writeFile(DEMO + '/split-a.js', Array.from({ length: 100 }, (_, i) => `const value${i} = ${i};`).join('\n'));
  await api.fs.writeFile(DEMO + '/split-b.ts', 'const greeting: string = "Hello";\ngreeting.toUpperCase();');
  await w.openFile(DEMO + '/split-a.js');
  const a = w.S.active, left = w.groups.groups[0];
  left.editor.setSel({ line: 5, col: 2 }, { line: 5, col: 2 });
  left.editor.input.dispatchEvent(new KeyboardEvent('keydown', { key: '\\', bubbles: true, cancelable: true, metaKey: /Mac/.test(navigator.platform), ctrlKey: !/Mac/.test(navigator.platform) }));
  const right = w.groups.groups[1];
  check('split shortcut creates and focuses a second pane', !!right && w.groups.active === right);
  check('split views share one document and buffer', left.active === a && right.active === a && left.editor.buffer === right.editor.buffer && w.S.docs.filter((d) => d.path === a.path).length === 1);
  check('independent tab bars show the file', left.tabs.querySelectorAll('.tab').length === 1 && right.tabs.querySelectorAll('.tab').length === 1);
  right.editor.setSel({ line: 20, col: 2 }, { line: 20, col: 2 }); right.editor.scroller.scrollTop = 300;
  right.editor.typeText('X');
  check('typing in right view updates left buffer', left.editor.buffer.getLine(20).includes('X'));
  check('carets and scroll positions are independent', left.editor.head.line === 5 && right.editor.head.line === 20 && left.editor.scroller.scrollTop !== right.editor.scroller.scrollTop);
  w.focusPane(left);
  left.editor.input.dispatchEvent(new KeyboardEvent('keydown', { key: '2', bubbles: true, cancelable: true, metaKey: /Mac/.test(navigator.platform), ctrlKey: !/Mac/.test(navigator.platform) }));
  check('focus shortcut targets the right pane', w.editor === right.editor && w.S.active === right.active);
  await w.closeDoc(a, right);
  check('closing a shared dirty view keeps edits without closing the document', w.S.docs.includes(a) && a.buffer.dirty && right.docs.length === 0 && left.docs.includes(a));
  await w.openFile(DEMO + '/split-b.ts');
  const b = w.S.active;
  check('new files open only in the focused pane', right.docs.includes(b) && !left.docs.includes(b));
  w.runCommand('find');
  check('find widget belongs to focused pane', right.findWidget.isOpen && !left.findWidget.isOpen);
  right.findWidget.close();
  right.editor.setSel({ line: 1, col: 10 }, { line: 1, col: 10 }); right.editor.focus(); right.editor.updateCompletion(true);
  check('right pane has semantic completion', await waitFor(() => right.editor.completion?.items.some((i) => i.label === 'toUpperCase')));
  right.editor.closeCompletion();
  const sash = document.querySelector('#sash-editors');
  sash.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true, cancelable: true }));
  check('divider can resize with keyboard', w.groups.ratio > 0.5);
  const x = sash.getBoundingClientRect().left;
  sash.dispatchEvent(new MouseEvent('mousedown', { clientX: x, bubbles: true, cancelable: true }));
  window.dispatchEvent(new MouseEvent('mousemove', { clientX: x - 80, bubbles: true }));
  window.dispatchEvent(new MouseEvent('mouseup', { bubbles: true }));
  check('divider supports pointer dragging', w.groups.ratio < 0.55 && w.groups.ratio >= 0.25);
  sash.dispatchEvent(new MouseEvent('dblclick', { bubbles: true }));
  check('divider resets to equal widths', w.groups.ratio === 0.5);
  w.moveEditor(b, right, left);
  check('moving a file transfers its tab without duplicating the document', left.docs.includes(b) && !right.docs.includes(b) && w.S.docs.filter((d) => d === b).length === 1);
  w.moveEditor(b, left, right);
  await w.openDocsPage();
  check('page tabs work alongside a code editor', w.S.active.page && !right.pageHost.el.hidden && left.active === a && left.pageHost.el.hidden);
  w.joinEditors();
  check('join preserves all documents and removes split layout', w.groups.groups.length === 1 && w.S.docs.includes(a) && w.S.docs.includes(b) && document.querySelector('#sash-editors').hidden);
  await w.openFile(a.path); w.splitEditor(); await w.openFile(b.path);
  const activeRight = w.groups.groups[1];
  w.setSplitRatio(0.6);
  await w.checkpointSession();
  const saved = (await api.session.get()).snapshot;
  check('session checkpoint includes group membership and active pane', saved.layout.groups.length === 2 && saved.layout.activeGroup === 'right' && saved.layout.ratio === 0.6);
  const host = document.querySelector('#editor-panes'); const oldWidth = host.style.width;
  host.style.width = '620px'; host.style.flex = 'none'; await wait(150);
  check('narrow panes keep both editors within bounds', left.root.getBoundingClientRect().width + activeRight.root.getBoundingClientRect().width <= host.getBoundingClientRect().width + 2);
  host.style.width = oldWidth; host.style.flex = ''; await wait(150);
  const inactiveTab = [...left.tabs.querySelectorAll('.tab')].find((t) => t.textContent.includes('split-b.ts'));
  inactiveTab.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true }));
  check('focusing an inactive tab preserves its click target', inactiveTab.isConnected);
  inactiveTab.click();
  check('clicking a tab in the inactive pane selects that file', w.groups.active === left && left.active === b);
  w.focusPane(activeRight);
  return out;
})();

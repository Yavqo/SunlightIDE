// Builds the file/folder icon set from Material Icon Theme (MIT, https://github.com/material-extensions/vscode-material-icon-theme).
// Output: src/renderer/icons/*.svg and src/renderer/icons/manifest.js. Runs after `npm install`.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const outDir = path.join(root, 'src', 'renderer', 'icons');
const pkgDir = path.join(root, 'node_modules', 'material-icon-theme');
if (!fs.existsSync(pkgDir)) { console.error('icons: material-icon-theme not installed; run npm install'); process.exit(1); }

const { generateManifest } = require('material-icon-theme');
const m = generateManifest();
const name = (id) => id; // icon ids double as file names
const defs = m.iconDefinitions;
const used = new Set();
const use = (id) => { if (id && defs[id]) used.add(id); return id; };

const lower = (obj) => Object.fromEntries(Object.entries(obj || {}).map(([k, v]) => [k, use(v)]));
const manifest = {
  file: use(m.file), folder: use(m.folder), folderOpen: use(m.folderExpanded), root: use(m.rootFolder), rootOpen: use(m.rootFolderExpanded),
  ext: lower(m.fileExtensions), names: lower(m.fileNames), folders: lower(m.folderNames), foldersOpen: lower(m.folderNamesExpanded),
  light: { ext: lower(m.light?.fileExtensions), names: lower(m.light?.fileNames), folders: lower(m.light?.folderNames), file: use(m.light?.file), folder: use(m.light?.folder) },
  lang: lower(m.languageIds),
};
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
let bytes = 0;
for (const id of used) {
  const src = path.join(pkgDir, 'icons', path.basename(defs[id].iconPath));
  if (!fs.existsSync(src)) continue;
  fs.copyFileSync(src, path.join(outDir, `${name(id)}.svg`));
  bytes += fs.statSync(src).size;
}
fs.writeFileSync(path.join(outDir, 'manifest.js'), `// Generated by scripts/icons.js. Do not edit.\nexport default ${JSON.stringify(manifest)};\n`);
fs.copyFileSync(path.join(pkgDir, 'LICENSE'), path.join(outDir, 'LICENSE-material-icon-theme.txt'));
console.log(`icons: ${used.size} svgs (${Math.round(bytes / 1024)} KB), manifest ${Math.round(fs.statSync(path.join(outDir, 'manifest.js')).size / 1024)} KB`);

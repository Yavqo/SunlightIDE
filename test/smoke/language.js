(async () => {
  const w = window.__sunlight, api = window.sunlight;
  const out = { passed: 0, failed: [], errors: [] };
  const check = (label, value) => { if (value) out.passed++; else out.failed.push(label); };
  const waitFor = async (fn) => { for (let i = 0; i < 200; i++) { if (fn()) return true; await new Promise((r) => setTimeout(r, 50)); } return false; };
  window.addEventListener('error', (e) => out.errors.push(e.message));
  await api.fs.writeFile(DEMO + '/model.ts', 'export const person = { name: "Ada", age: 36 };\n');
  const text = 'import { person } from "./model";\nconst wrong: string = person.age;\nperson.na';
  await api.fs.writeFile(DEMO + '/main.ts', text);
  await w.setRoot(DEMO);
  await w.openFile(DEMO + '/main.ts');
  const e = w.editor;
  e.setSel({ line: 2, col: 9 }, { line: 2, col: 9 }); e.focus();
  e.updateCompletion(true);
  check('semantic member completion appears in editor', await waitFor(() => e.completion?.items.some((i) => i.label === 'name')));
  e.completion.index = e.completion.items.findIndex((i) => i.label === 'name');
  e.acceptCompletion();
  check('semantic completion edits text', e.buffer.getLine(2) === 'person.name');
  check('type diagnostics render underlines', await waitFor(() => w.languageIntelligence.diagnostics.some((d) => d.code === 2322) && document.querySelector('.language-squiggle')));
  await w.languageIntelligence.hover({ line: 2, col: 2 });
  check('hover shows inferred type', !document.querySelector('.language-hover').hidden && /person/.test(document.querySelector('.language-hover').textContent));
  e.setSel({ line: 2, col: 2 }, { line: 2, col: 2 });
  e.input.dispatchEvent(new KeyboardEvent('keydown', { key: 'F12', bubbles: true, cancelable: true }));
  check('F12 opens imported definition', await waitFor(() => w.S.active.path === DEMO + '/model.ts'));
  e.setSel({ line: 0, col: 15 }, { line: 0, col: 15 });
  const renaming = w.languageIntelligence.rename();
  await waitFor(() => document.querySelector('.palette input'));
  const input = document.querySelector('.palette input');
  input.value = 'profile'; input.dispatchEvent(new Event('input'));
  input.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
  await renaming;
  check('rename changes declaration and imported references', w.S.active.buffer.getText().includes('const profile') && w.S.docs.find((d) => d.path === DEMO + '/main.ts').buffer.getText().includes('profile'));
  check('rename leaves affected files unsaved', w.S.docs.filter((d) => /(?:main|model)\.ts$/.test(d.path || '')).every((d) => d.buffer.dirty));
  e.undo();
  check('rename can be undone in the editor', e.buffer.getText().includes('const person'));
  await w.openFile(DEMO + '/main.ts');
  const original = e.doc;
  e.updateCompletion(true);
  w.newUntitled();
  await new Promise((r) => setTimeout(r, 250));
  check('late completions cannot overwrite another tab', e.doc !== original && !e.completion);
  w.S.active.setLang('typescript');
  e.edit({ line: 0, col: 0 }, { line: 0, col: 0 }, 'const invalid: number = "text";');
  check('unsaved files receive language diagnostics', await waitFor(() => w.languageIntelligence.diagnostics.some((d) => d.code === 2322)));
  return out;
})();

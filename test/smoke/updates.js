(async () => {
  const w = window.__sunlight, api = window.sunlight;
  const out = { passed: 0, failed: [], errors: [] };
  const check = (label, value) => { if (value) out.passed++; else out.failed.push(label); };
  const wait = (ms) => new Promise((r) => setTimeout(r, ms));
  window.addEventListener('error', (e) => out.errors.push(e.message));
  await w.checkExtensionUpdates();
  const entry = w.extPanel.catalog.find((e) => e.id === 'sunlight.text-tools');
  await w.installExtension(entry, { skipConfirm: true });
  const update = { ...w.extPanel.catalog.find((e) => e.id === entry.id), version: '2.0.0', updateAvailable: true };
  const catalog = { catalog: [update], installed: w.extPanel.installed, registry: '', error: null };
  // Synthetic future catalog versions exercise the notification UI without modifying bundled packages.
  w.extensionUpdates.observe(catalog);
  const badge = document.querySelector('[data-view="ext"] .badge');
  check('extensions icon displays available update count', !badge.hidden && badge.textContent === '1');
  const notices = () => [...document.querySelectorAll('.toast')].filter((t) => t.textContent.includes('2.0.0 is available'));
  check('new version has actionable notification', notices().length === 1 && notices()[0].querySelector('button'));
  w.extensionUpdates.observe(catalog);
  check('repeated checks do not repeat notification', notices().length === 1);
  await wait(100);
  check('notification version survives in persisted state', (await api.state.get()).extensionUpdatesSeen.some((s) => s.includes(`${entry.id}@2.0.0`)));
  notices()[0].querySelector('button').click();
  check('review action opens updates filter', !document.querySelector('#panel-ext').hidden && w.extPanel.filter === 'updates');
  await w.extPanel.refresh();
  check('current store clears resolved update badge', badge.hidden);
  w.S.settings.extensionUpdateNotifications = false;
  w.extPanel.hooks.refreshed({ ...catalog, catalog: [{ ...update, version: '3.0.0' }] });
  check('muted notifications still show update count', !badge.hidden);
  check('muted notifications produce no toast', ![...document.querySelectorAll('.toast')].some((t) => t.textContent.includes('3.0.0 is available')));
  w.S.settings.extensionUpdateNotifications = true;
  w.extPanel.hooks.refreshed({ ...catalog, catalog: [{ ...update, version: '3.0.0' }] });
  check('reenabling notifications announces unseen version', [...document.querySelectorAll('.toast')].some((t) => t.textContent.includes('3.0.0 is available')));
  await w.checkExtensionUpdates(true);
  check('manual check reports up to date', [...document.querySelectorAll('.toast')].some((t) => /All installed extensions are up to date/.test(t.textContent)));
  check('manual checks never install an update', w.extPanel.installed.find((e) => e.id === entry.id).manifest.version === entry.version);
  const before = [...document.querySelectorAll('.toast')].filter((t) => /All installed extensions are up to date/.test(t.textContent)).length;
  const first = w.checkExtensionUpdates(true), second = w.checkExtensionUpdates(true);
  await Promise.all([first, second]);
  check('overlapping manual checks share one request and notification', first === second && [...document.querySelectorAll('.toast')].filter((t) => /All installed extensions are up to date/.test(t.textContent)).length === before + 1);
  w.runCommand('settings');
  check('notification preference is in Settings', !!document.querySelector('[aria-label="extensionUpdateNotifications"]'));
  document.querySelector('.dialog-actions button').click();
  return out;
})();
